"""Fit the aero tables of the reference model to V3Kite.jl results.

Input: the CSV written by ``scripts/v3kite_extract_coeffs.jl`` (one row per depower
setting with the settled mean AoA, CL and non-tether CD of the full V3Kite.jl model).
Output: ``softkite/data/v3_aero_v3kite.yaml``, same format as ``softkite/data/v3_aero.yaml``, with

* CL(alpha), CD(alpha): quadratic least-squares fits over the identified AoA range,
  joined continuously to the VSM table (shape only) outside that range;
* alpha_trim(u_p): the identified mean AoA per depower (depower axis ``u_p``);
* CS_beta and the CM table are taken from the VSM table (the parked V3Kite runs are
  all at trim, where CM about the KCU is zero, so they carry no CM information).

Use it with ``AeroModel("softkite/data/v3_aero_v3kite.yaml", cd_kcu_area=0)`` or ``aero_file`` in settings.
"""

from __future__ import annotations

import argparse
import datetime as _dt
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]


def blend(alpha, fit, base, a_lo, a_hi):
    """Fit inside [a_lo, a_hi]; outside, the base table offset to join continuously."""
    out = np.polyval(fit, alpha)
    lo, hi = alpha < a_lo, alpha > a_hi
    out[lo] = np.interp(alpha[lo], alpha, base) - np.interp(a_lo, alpha, base) + np.polyval(fit, a_lo)
    out[hi] = np.interp(alpha[hi], alpha, base) - np.interp(a_hi, alpha, base) + np.polyval(fit, a_hi)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("csv")
    ap.add_argument("--base", default=str(ROOT / "softkite" / "data" / "v3_aero.yaml"))
    ap.add_argument("--out", default=str(ROOT / "softkite" / "data" / "v3_aero_v3kite.yaml"))
    ap.add_argument("--deg", type=int, default=2, help="polynomial degree of the fits")
    args = ap.parse_args()

    df = pd.read_csv(args.csv).dropna(subset=["aoa_mean_deg", "cl", "cd"]).sort_values("depower")
    if len(df) < args.deg + 1:
        raise SystemExit(f"need at least {args.deg + 1} valid rows, got {len(df)}")
    base = yaml.safe_load(open(args.base))
    alpha = np.asarray(base["alpha_deg"], float)
    a = df["aoa_mean_deg"].to_numpy()
    fit_cl = np.polyfit(a, df["cl"], args.deg)
    fit_cd = np.polyfit(a, df["cd"], args.deg)
    a_lo, a_hi = a.min(), a.max()
    cl = blend(alpha, fit_cl, np.asarray(base["cl"], float), a_lo, a_hi)
    cd = blend(alpha, fit_cd, np.asarray(base["cd"], float), a_lo, a_hi)

    res_cl = df["cl"] - np.polyval(fit_cl, a)
    res_cd = df["cd"] - np.polyval(fit_cd, a)
    print(f"{len(df)} depower settings, AoA {a_lo:.2f} .. {a_hi:.2f} deg")
    print(f"CL fit {np.round(fit_cl, 5)}  rms {np.sqrt(np.mean(res_cl ** 2)):.4f}")
    print(f"CD fit {np.round(fit_cd, 5)}  rms {np.sqrt(np.mean(res_cd ** 2)):.4f}")

    # NOTE: V3Kite's compute_drag_coeff already contains bridle and KCU drag; the
    # reference model adds cd_kcu_area/S on top, so pass cd_kcu_area=0 with this file.
    out = {
        "provenance": {
            "generated_by": "scripts/fit_v3kite_logs.py",
            "date": _dt.date.today().isoformat(),
            "method": "Parked V3Kite.jl runs at constant tether length, one per depower; "
                      "settled span-mean AoA, CL and non-tether CD (incl. bridle and KCU). "
                      f"Polynomial degree {args.deg}. Outside the identified AoA range the "
                      "VSM table shape is used.",
            "source_csv": str(Path(args.csv).resolve()),
            "kcu_drag_included": True,
        },
        "reference": base["reference"],
        "alpha_deg": alpha.tolist(),
        "cl": np.round(cl, 5).tolist(),
        "cd": np.round(cd, 5).tolist(),
        "cs_beta": base.get("cs_beta", 1.0),
        "depower": {
            "description": "relative depower u_p and the identified trim AoA",
            "u_p": df["depower"].round(4).tolist(),
            "alpha_trim_deg": df["aoa_mean_deg"].round(3).tolist(),
        },
        "v3kite_points": {k: df[k].round(5).tolist() for k in
                          ["depower", "aoa_mean_deg", "cl", "cd", "v_app", "force", "elevation_deg"]
                          if k in df},
    }
    with open(args.out, "w") as f:
        f.write("# Generated by scripts/fit_v3kite_logs.py - do not edit by hand.\n")
        yaml.safe_dump(out, f, sort_keys=False, default_flow_style=None, width=120)
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
